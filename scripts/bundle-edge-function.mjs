#!/usr/bin/env node
// Bundle a Supabase Edge Function entrypoint into a single self-contained
// TypeScript file by inlining local relative imports (../_shared/*.ts).
// Remote URL imports (esm.sh, deno.land) are kept as-is for the Deno runtime.
//
// Usage: node scripts/bundle-edge-function.mjs <entry.ts> <out.ts>

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const [entry, out] = process.argv.slice(2);
if (!entry || !out) {
  console.error('Usage: node scripts/bundle-edge-function.mjs <entry.ts> <out.ts>');
  process.exit(1);
}

const emitted = new Set();
const remoteImports = new Set();

function stripExports(code) {
  return code
    .replace(/^export\s+default\s+/gm, '')
    .replace(/^export\s+(?=(async\s+)?function\s)/gm, '')
    .replace(/^export\s+(?=const\s|let\s|var\s|class\s|interface\s|type\s)/gm, '')
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '');
}

function inline(filePath) {
  const abs = resolve(filePath);
  if (emitted.has(abs)) return '';
  emitted.add(abs);

  const code = readFileSync(abs, 'utf8');
  const lines = code.split('\n');
  const chunks = [];
  let i = 0;

  while (i < lines.length) {
    const line = lines[i];
    const m = line.match(/^import\s/);
    if (m) {
      // Collect the full (possibly multiline) import statement.
      let stmt = line;
      while (!stmt.includes('from') && i + 1 < lines.length) {
        i += 1;
        stmt += '\n' + lines[i];
      }
      const fromMatch = stmt.match(/from\s+["']([^"']+)["']/);
      if (fromMatch) {
        const spec = fromMatch[1];
        if (spec.startsWith('.')) {
          const dep = resolve(dirname(abs), spec);
          chunks.push(`// ── inlined: ${spec} (from ${abs.split('/').slice(-2).join('/')}) ──`);
          chunks.push(inline(dep));
        } else {
          remoteImports.add(stmt.trim());
        }
      }
      i += 1;
      continue;
    }
    chunks.push(line);
    i += 1;
  }
  return stripExports(chunks.join('\n'));
}

const body = inline(entry);
const header = [
  `// AUTO-GENERATED BUNDLE of ${entry} — do not edit directly.`,
  `// Generated by scripts/bundle-edge-function.mjs for single-file deployment.`,
  '',
  ...[...remoteImports],
  '',
].join('\n');

writeFileSync(out, header + '\n' + body);
console.log(`bundled ${entry} -> ${out} (${(header + body).length} bytes)`);
