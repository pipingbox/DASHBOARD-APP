-- TESTFIXTURE-006 — PB-ENT-E0B-BASELINE-DDL-001: esquema sintético para probar
-- el extractor docs/baseline/extract-ddl-baseline.sql.
--
-- Crea en `public` de una base scratch (desechable) dos tablas `e0bh_*` que
-- ejercitan TODAS las categorías que el extractor debe capturar:
--   columnas (tipo/UDT/null/default/identity/generated/sequence), PK, FK
--   (con acciones), UNIQUE, CHECK, índice plano, índice parcial+expresión,
--   trigger enabled, trigger disabled, RLS ENABLE, RLS FORCE, policies
--   (qual + with_check) con función dependiente, función dependiente de un
--   DEFAULT, grants a roles Supabase-like, enum, domain, composite.
--
-- NO es un stub de producción: los nombres e0bh_* son exclusivos del harness.
-- ══════════════════════════════════════════════════════════════════════════════

-- Roles Supabase-like (idempotente)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN CREATE ROLE anon NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN CREATE ROLE service_role NOLOGIN; END IF;
END
$$;

-- Tipos no built-in
DROP TYPE IF EXISTS public.e0bh_status CASCADE;
CREATE TYPE public.e0bh_status AS ENUM ('active', 'suspended', 'archived');

DROP DOMAIN IF EXISTS public.e0bh_email CASCADE;
CREATE DOMAIN public.e0bh_email AS text CHECK (VALUE ~ '^[^@]+@[^@]+$');

DROP TYPE IF EXISTS public.e0bh_address CASCADE;
CREATE TYPE public.e0bh_address AS (street text, city text, zip text);

-- Funciones dependientes (policy qual, trigger, default)
CREATE OR REPLACE FUNCTION public.e0bh_is_allowed(p_id uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT true $$;

CREATE OR REPLACE FUNCTION public.e0bh_touch()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.qty := NEW.qty + 0; -- no-op; solo para tener tgfoid
  RETURN NEW;
END
$$;

CREATE OR REPLACE FUNCTION public.e0bh_default_code()
RETURNS text LANGUAGE sql STABLE AS $$ SELECT 'E0BH-DEFAULT' $$;

-- Tabla padre: RLS ENABLE + FORCE, policy, grants
DROP TABLE IF EXISTS public.e0bh_main CASCADE;
DROP TABLE IF EXISTS public.e0bh_parent CASCADE;

CREATE TABLE public.e0bh_parent (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  label text NOT NULL
);

CREATE TABLE public.e0bh_main (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  parent_id uuid REFERENCES public.e0bh_parent(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  status public.e0bh_status NOT NULL DEFAULT 'active',
  email public.e0bh_email,
  code text NOT NULL DEFAULT public.e0bh_default_code(),
  qty integer NOT NULL DEFAULT 0 CHECK (qty >= 0),
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  code_upper text GENERATED ALWAYS AS (upper(code)) STORED,
  address public.e0bh_address,
  tags text[],
  notes text,
  CONSTRAINT e0bh_main_code_uniq UNIQUE (code)
);

-- Índice plano
CREATE INDEX e0bh_main_qty_idx ON public.e0bh_main (qty);
-- Índice parcial + expresión
CREATE UNIQUE INDEX e0bh_main_lowercode_active_idx ON public.e0bh_main (lower(code)) WHERE status = 'active';

-- Trigger enabled
CREATE TRIGGER e0bh_main_touch_trg
  BEFORE UPDATE ON public.e0bh_main
  FOR EACH ROW EXECUTE FUNCTION public.e0bh_touch();
-- Trigger disabled (estado D)
CREATE TRIGGER e0bh_main_touch_disabled_trg
  BEFORE DELETE ON public.e0bh_main
  FOR EACH ROW EXECUTE FUNCTION public.e0bh_touch();
ALTER TABLE public.e0bh_main DISABLE TRIGGER e0bh_main_touch_disabled_trg;

-- RLS: main ENABLE (sin FORCE), parent ENABLE + FORCE
ALTER TABLE public.e0bh_main ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.e0bh_parent ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.e0bh_parent FORCE ROW LEVEL SECURITY;

-- Policies: SELECT con qual que depende de función; INSERT con with_check
CREATE POLICY e0bh_main_select ON public.e0bh_main
  FOR SELECT TO authenticated
  USING (public.e0bh_is_allowed(id));
CREATE POLICY e0bh_main_insert ON public.e0bh_main
  FOR INSERT TO authenticated
  WITH CHECK (qty >= 0);
CREATE POLICY e0bh_parent_select ON public.e0bh_parent
  FOR SELECT TO authenticated
  USING (true);

-- Grants
GRANT SELECT ON public.e0bh_main TO authenticated;
GRANT SELECT, INSERT ON public.e0bh_main TO service_role;
GRANT SELECT ON public.e0bh_parent TO anon;

-- Sonda de discovery: tabla NO objetivo cuyo nombre matchea los patrones
-- '%job%' del extractor; debe aparecer en candidate_tables.
DROP TABLE IF EXISTS public.e0bh_job_probe CASCADE;
CREATE TABLE public.e0bh_job_probe (id int PRIMARY KEY);
